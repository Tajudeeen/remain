// Build-time only: pins public deployment provenance to the exact Git tree.
// Do not print environment variables or keys into bundles or logs.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const dir=fileURLToPath(new URL('../',import.meta.url));
const commit=execFileSync('git',['rev-parse','--verify','HEAD'],{
  cwd:dir,encoding:'utf8',stdio:['ignore','pipe','ignore'],timeout:5000
}).trim();
if (!/^[a-f0-9]{40}$/.test(commit)) throw new Error('UNVERIFIED_GIT_BUILD_IDENTITY');
writeFileSync(new URL('../cloudflare/build-identity.js',import.meta.url),
  '// Generated by scripts/stamp-cloudflare-build.js. Do not edit manually.\n'+
  'export const BUILD_SHA = '+JSON.stringify(commit)+';\n',
  {encoding:'utf8',mode:0o600});
process.stdout.write('REMAIN_BUILD_IDENTITY: '+commit+'\n');
